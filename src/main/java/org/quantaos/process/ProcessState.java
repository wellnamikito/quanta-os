package org.quantaos.process;

/** Состояния процесса в учебной модели планировщика.*/
public enum ProcessState {
    /** Процесс ждет процессор в одной из очередей готовности. */
    READY,

    /** Процесс сейчас выполняется на процессоре. */
    RUNNING,

    /** Процесс сам ждет событие ввода-двывода или был заблокирован командой */
    BLOCKED,

    /** Процесс завершён и больше не будет поставлен в очередь. */
    TERMINATED
}
